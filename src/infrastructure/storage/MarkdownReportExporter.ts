import * as fs from 'node:fs/promises';
import * as path from 'node:path';
import {
  AuditReport,
  IReportExporter,
  ExportResult,
  JobLead,
} from '../../domain/index.js';

export interface MarkdownExporterOptions {
  jobLead?: JobLead;
}

export class MarkdownReportExporter implements IReportExporter {
  private jobLead?: JobLead;

  constructor(options?: MarkdownExporterOptions) {
    this.jobLead = options?.jobLead;
  }

  public async export(
    report: AuditReport,
    destinationPath?: string
  ): Promise<ExportResult> {
    const { summary, findings, repoMetadata } = report;

    const lines: string[] = [
      `# 🛡️ Security & Architecture Audit: ${repoMetadata.name}`,
      ``,
      `> Generated by **AI Code Auditor** on ${new Date(report.generatedAt).toUTCString()}`,
      ``,
      `### Executive Summary`,
      `- **Target**: \`${repoMetadata.name}\` (${repoMetadata.sourceType})`,
      `- **Health Score**: **${summary.healthScore} / 100** (${summary.riskLevel} RISK)`,
      `- **Total Files Audited**: ${repoMetadata.totalFiles} (~${repoMetadata.totalTokens.toLocaleString()} tokens)`,
      `- **Overview**: ${summary.executiveSummary}`,
      ``,
      `### Findings Breakdown`,
      `| Severity | Count |`,
      `| :--- | :--- |`,
      `| 🔴 **CRITICAL** | ${summary.bySeverity.CRITICAL} |`,
      `| 🟠 **HIGH** | ${summary.bySeverity.HIGH} |`,
      `| 🟡 **MEDIUM** | ${summary.bySeverity.MEDIUM} |`,
      `| 🟢 **LOW** | ${summary.bySeverity.LOW} |`,
      `| ⚪ **INFO** | ${summary.bySeverity.INFO} |`,
      ``,
    ];

    if (this.jobLead) {
      lines.push(
        `---`,
        `### 🚀 Suggested Outreach Pitch`,
        `> **Estimated Scope**: ${this.jobLead.estimatedRemediationHours} hours | **Quote Range**: ${this.jobLead.suggestedQuoteUsd}`,
        ``,
        '```text',
        this.jobLead.pitchDraft,
        '```',
        ``
      );
    }

    lines.push(`---`, `## Discovered Vulnerabilities & Defects`, ``);

    for (const f of findings) {
      lines.push(
        `### [${f.severity}] ${f.title} (${f.id})`,
        `- **Location**: \`${f.filePath}\` (Lines ${f.lineStart} - ${f.lineEnd})`,
        f.cweId ? `- **Classification**: \`${f.cweId}\`` : '',
        `- **Category**: ${f.category}`,
        ``,
        `**Vulnerable Code:**`,
        '```' + (f.filePath.endsWith('.ts') ? 'typescript' : 'javascript'),
        f.snippet,
        '```',
        ``,
        `**Explanation:** ${f.explanation}`,
        ``,
        `**Impact:** ${f.impact}`,
        ``
      );

      if (f.remediation) {
        lines.push(
          `**Remediation:** ${f.remediation.explanation}`,
          ``,
          '```diff',
          f.remediation.unifiedDiff,
          '```',
          ``
        );
      }
      lines.push(`---`, ``);
    }

    const content = lines.filter(Boolean).join('\n');

    let finalPath = destinationPath;
    if (finalPath) {
      const resolved = path.resolve(finalPath);
      await fs.mkdir(path.dirname(resolved), { recursive: true });
      await fs.writeFile(resolved, content, 'utf-8');
      finalPath = resolved;
    }

    return {
      filePath: finalPath,
      content,
    };
  }
}
